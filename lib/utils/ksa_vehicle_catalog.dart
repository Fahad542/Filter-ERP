  static List<String> get makes => _modelsByMake.keys.toList(growable: false);

  static List<String> modelsForMake(String make) {
    final key = _canonicalMake(make);
    if (key == null) return const [];
    return _modelsByMake[key] ?? const [];
  }

  static bool hasMake(String make) => _canonicalMake(make) != null;

  static String? _canonicalMake(String make) {
    final needle = make.trim().toLowerCase();
    if (needle.isEmpty) return null;
    for (final key in _modelsByMake.keys) {
      if (key.toLowerCase() == needle) return key;
    }
    return null;
  }
